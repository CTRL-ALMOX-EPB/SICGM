function getItensPorDeposito(deposito, tipoContagem) {
    const config = DEPOSITOS_CONFIG[deposito];
    if (!config) return null;
    
    if (deposito === '1050') {
        return 'padrao';
    }
    
    if (tipoContagem === 'semanal') {
        return config.itens_semanal || [];
    }
    
    if (deposito === '1855' && tipoContagem === 'diaria') {
        return 'trafos_only';
    }
    
    return [];
}

function depositoTemContagem(deposito, tipoContagem) {
    const config = DEPOSITOS_CONFIG[deposito];
    if (!config) return false;
    return config.contagens && config.contagens[tipoContagem] === true;
}